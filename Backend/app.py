# ─── Database Dependency ──────────────────────────────────────────────────────

def get_db():
    """
    FastAPI dependency — creates a new DB session per request and closes it after.
    Used in every endpoint that needs database access.

    Usage in endpoint:
        @app.get("/leads")
        def get_leads(db: Session = Depends(get_db)):
            ...
    """
    db = SyncSessionLocal()
    try:
        yield db
    finally:
        db.close()


