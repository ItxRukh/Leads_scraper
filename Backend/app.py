@app.get("/leads", tags=["Leads"])
def get_leads(
    niche:     Optional[str]  = Query(None, description="Filter by niche e.g. 'toys'"),
    city:      Optional[str]  = Query(None, description="Filter by city e.g. 'Miami FL'"),
    tier:      Optional[str]  = Query(None, description="Filter by tier: hot | warm | cold"),
    min_score: Optional[int]  = Query(None, description="Minimum lead score"),
    search:    Optional[str]  = Query(None, description="Free-text search across name, email, phone"),
    pipeline_stage: Optional[str] = Query(None, description="Filter by CRM pipeline stage e.g. 'audited'"),
    year:      Optional[int]  = Query(None, ge=2000, le=2100, description="Filter by scraped_at year. Combine with month for a single month."),
    month:     Optional[int]  = Query(None, ge=1, le=12, description="Filter by scraped_at month (1-12). Requires year."),
    stuck:     bool           = Query(False, description="Stuck Leads filter — only leads with no possible outreach path (no email AND no phone, or Do-Not-Contact)"),
    batch:     Optional[int]  = Query(None, description="Only the leads of this import"),
    skip:      int            = Query(0,    description="Pagination offset"),
    limit:     int            = Query(100,  description="Max results to return"),
    db: Session = Depends(get_db),
):
    """
    Returns a filtered, paginated list of leads.
    Used by the React frontend to populate the All Leads table.
    """
    tier_enum  = LeadTier(tier) if tier else None
    stage_enum = PipelineStage(pipeline_stage) if pipeline_stage else None

    # Pagination happens in SQL (LIMIT/OFFSET) instead of loading every
    # matching row into Python — keeps this fast even at 10,000+ leads.
    leads, total = LeadCRUD.search_paginated(
        db,
        niche=niche,
        city=city,
        tier=tier_enum,
        min_score=min_score,
        q=search,
        pipeline_stage=stage_enum,
        year=year,
        month=month,
        stuck_only=stuck,
        batch_id=batch,
        skip=skip,
        limit=limit,
    )

    from scripts.outreach_reason import get_outreach_status_bulk
    status_by_lead = get_outreach_status_bulk(leads, db)
    import lead_journey
    journey_by_lead = lead_journey.journeys(db, leads)

    return {
        "total": total,
        "page_size": limit,
        "offset": skip,
        "leads": [_serialize_lead(lead, status_by_lead.get(lead.id), journey_by_lead.get(lead.id)) for lead in leads],
    }


@app.get("/leads/status-summary", tags=["Leads"])
def leads_status_summary(db: Session = Depends(get_db)):
    """How many leads are at each step ("Where it is"), for the cards on the Leads page."""
    import lead_journey
    leads = db.query(Lead).all()
    counts: dict = {}
    for journey in lead_journey.journeys(db, leads).values():
        counts[journey["key"]] = counts.get(journey["key"], 0) + 1
    return {"total": len(leads), "by_step": counts}


