# ─── Global Exception Handler ─────────────────────────────────────────────────
# Catches anything that isn't an intentional HTTPException, logs the full
# stack trace (to logs/errors.log, and to Sentry if SENTRY_DSN is set), and
# returns a clean generic error instead of leaking a raw Python traceback
# to the client. Without this, an unhandled crash in any endpoint could
# silently 500 with no record anywhere.
@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    logger.error(f"Unhandled exception on {request.method} {request.url.path}: {exc}")
    return JSONResponse(
        status_code=500,
        content={"detail": "Internal server error. This has been logged."},
    )


