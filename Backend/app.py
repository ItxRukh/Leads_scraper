class PipelineUpdateRequest(BaseModel):
    stage: str  # Must match PipelineStage enum values


@app.put("/leads/{lead_id}/pipeline", tags=["CRM"])
def update_pipeline_stage(
    lead_id: int,
    req: PipelineUpdateRequest,
    db: Session = Depends(get_db),
):
    """
    Manually moves a lead to a different CRM pipeline stage.
    Used when a sales rep updates the stage from the dashboard (Kanban board).

    Valid stages: scraped | linkedin_enriched | audited | email_verified |
                  email_sent | email_opened | replied | call_placed |
                  whatsapp_sent | demo_booked | onboarded | rejected | dnc

    Dragging a card to/from the "DNC" column used to only relabel the
    pipeline_stage — it didn't actually add/remove a DNC list entry or
    touch do_not_contact, so outreach kept going out (or stayed silently
    blocked) regardless of what the board showed. This now keeps the
    Kanban board, the DNC list, and do_not_contact in sync with each other,
    the same way the DNC page's add/remove actions already do.
    """
    try:
        stage_enum = PipelineStage(req.stage)
    except ValueError:
        raise HTTPException(status_code=400, detail=f"Invalid pipeline stage: {req.stage}")

    lead = LeadCRUD.get_by_id(db, lead_id)
    if not lead:
        raise HTTPException(status_code=404, detail=f"Lead {lead_id} not found")

    was_dnc = lead.pipeline_stage == PipelineStage.DNC

    if stage_enum == PipelineStage.DNC and not was_dnc:
        # Moving TO the DNC column — actually block outreach, not just relabel.
        LeadCRUD.mark_do_not_contact(db, lead_id)  # sets do_not_contact=True, pipeline_stage=DNC, score=0, tier=COLD
        if lead.email and not DNCCrud.is_on_dnc(db, email=lead.email):
            DNCCrud.add_to_dnc(db, email=lead.email, reason="pipeline_kanban")
        if lead.phone and not DNCCrud.is_on_dnc(db, phone=lead.phone):
            DNCCrud.add_to_dnc(db, phone=lead.phone, reason="pipeline_kanban")

    elif was_dnc and stage_enum != PipelineStage.DNC:
        # Moving AWAY from the DNC column — actually unblock outreach.
        if lead.email:
            action_remove(db, email=lead.email)
        if lead.phone:
            action_remove(db, phone=lead.phone)
        lead.do_not_contact = False
        LeadCRUD.update_pipeline_stage(db, lead_id, stage_enum)

    else:
        LeadCRUD.update_pipeline_stage(db, lead_id, stage_enum)

    return {"status": "updated", "lead_id": lead_id, "new_stage": req.stage}


