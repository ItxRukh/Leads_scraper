@app.get("/analytics/overview", tags=["Analytics"])
def get_analytics_overview(
    range: Optional[str] = Query(None, description="7d, 30d, 90d, or omit/'all' for all-time"),
    month: Optional[int] = Query(None, ge=1, le=12, description="1-12. Combine with year to filter a specific month."),
    year:  Optional[int] = Query(None, ge=2000, le=2100, description="e.g. 2026. Used alone for a full year, or with month for a specific month."),
    db: Session = Depends(get_db),
):
    """
    Returns high-level stats for the Analytics dashboard tab:
      - Total leads by source
      - Leads by tier (hot/warm/cold)
      - Email sent / opened / replied counts
      - Call outcomes breakdown
      - WhatsApp delivery stats
      - DNC list size

    `range` filters every count down to activity in the last N days
    (matches the 7d / 30d / 90d pills in the frontend). Omit or pass
    'all' for all-time totals (the previous default behaviour).

    `month` / `year` filter down to a specific calendar month or year
    instead — pass `year` alone for the whole year, or `year`+`month`
    together for a single month. These take priority over `range` when
    provided.
    """
    RANGE_DAYS = {"7d": 7, "30d": 30, "90d": 90}
    since = None
    until = None

    if year is not None:
        if month is not None:
            since = datetime(year, month, 1)
            until = datetime(year + 1, 1, 1) if month == 12 else datetime(year, month + 1, 1)
        else:
            since = datetime(year, 1, 1)
            until = datetime(year + 1, 1, 1)
    elif range in RANGE_DAYS:
        since = datetime.utcnow() - timedelta(days=RANGE_DAYS[range])

    leads_q = db.query(Lead)
    emails_q = db.query(EmailLog)
    calls_q = db.query(CallLog)
    wa_q = db.query(WhatsAppLog)
    if since is not None:
        leads_q = leads_q.filter(Lead.scraped_at >= since)
        emails_q = emails_q.filter(EmailLog.sent_at >= since)
        calls_q = calls_q.filter(CallLog.called_at >= since)
        wa_q = wa_q.filter(WhatsAppLog.sent_at >= since)
    if until is not None:
        leads_q = leads_q.filter(Lead.scraped_at < until)
        emails_q = emails_q.filter(EmailLog.sent_at < until)
        calls_q = calls_q.filter(CallLog.called_at < until)
        wa_q = wa_q.filter(WhatsAppLog.sent_at < until)

    total_leads = leads_q.count()

    # Leads by tier
    hot_count  = leads_q.filter(Lead.tier == LeadTier.HOT).count()
    warm_count = leads_q.filter(Lead.tier == LeadTier.WARM).count()
    cold_count = leads_q.filter(Lead.tier == LeadTier.COLD).count()

    # Email stats
    emails_sent    = emails_q.count()
    emails_opened  = emails_q.filter(EmailLog.email_opened == True).count()
    emails_replied = emails_q.filter(EmailLog.replied == True).count()

    # Call stats
    calls_total = calls_q.count()

    def _call_outcome_count(outcome: CallOutcome) -> int:
        return calls_q.filter(CallLog.outcome == outcome).count()

    calls_interested     = _call_outcome_count(CallOutcome.INTERESTED)
    calls_not_interested = _call_outcome_count(CallOutcome.NOT_INTERESTED)
    calls_callback       = _call_outcome_count(CallOutcome.CALLBACK)
    calls_no_answer      = _call_outcome_count(CallOutcome.NO_ANSWER)
    calls_wrong_number   = _call_outcome_count(CallOutcome.WRONG_NUMBER)
    calls_voicemail      = _call_outcome_count(CallOutcome.VOICEMAIL)

    # Average call duration overall + broken down by outcome
    all_durations = [d for (d,) in calls_q.with_entities(CallLog.duration_sec).filter(CallLog.duration_sec.isnot(None)).all()]
    avg_duration_overall = round(sum(all_durations) / len(all_durations), 1) if all_durations else 0

    avg_duration_by_outcome = {}
    for outcome in CallOutcome:
        durations = [
            d for (d,) in calls_q.with_entities(CallLog.duration_sec)
            .filter(CallLog.outcome == outcome, CallLog.duration_sec.isnot(None))
            .all()
        ]
        avg_duration_by_outcome[outcome.value] = round(sum(durations) / len(durations), 1) if durations else 0

    # WhatsApp stats
    wa_sent      = wa_q.count()
    wa_replied   = wa_q.filter(WhatsAppLog.replied == True).count()
    wa_delivered = wa_q.filter(WhatsAppLog.delivery_status == "delivered").count()
    wa_read      = wa_q.filter(WhatsAppLog.delivery_status == "read").count()
    wa_failed    = wa_q.filter(WhatsAppLog.delivery_status == "failed").count()

    # DNC size — always all-time (do-not-contact list isn't a "range" metric)
    dnc_total = db.query(DNCList).count()

    # Onboarded leads — counted from the range-filtered lead set (by scraped_at,
    # since there's no separate "onboarded_at" timestamp on the Lead model yet)
    onboarded = leads_q.filter(
        Lead.pipeline_stage == PipelineStage.ONBOARDED
    ).count()

    return {
        "total_leads":     total_leads,
        "tiers": {
            "hot":  hot_count,
            "warm": warm_count,
            "cold": cold_count,
        },
        "emails": {
            "sent":    emails_sent,
            "opened":  emails_opened,
            "replied": emails_replied,
            "open_rate":  round(emails_opened  / emails_sent * 100, 1) if emails_sent else 0,
            "reply_rate": round(emails_replied / emails_sent * 100, 1) if emails_sent else 0,
        },
        "calls": {
            "total":          calls_total,
            "interested":     calls_interested,
            "not_interested": calls_not_interested,
            "callback":       calls_callback,
            "no_answer":      calls_no_answer,
            "wrong_number":   calls_wrong_number,
            "voicemail":      calls_voicemail,
            "avg_duration":   avg_duration_overall,
            "avg_duration_by_outcome": avg_duration_by_outcome,
        },
        "whatsapp": {
            "sent":      wa_sent,
            "replied":   wa_replied,
            "delivered": wa_delivered,
            "read":      wa_read,
            "failed":    wa_failed,
        },
        "dnc_total":  dnc_total,
        "onboarded":  onboarded,
    }


@app.get("/analytics/trend", tags=["Analytics"])
def get_analytics_trend(days: int = 7, db: Session = Depends(get_db)):
    """
    Real day-by-day activity for the last `days` days (default 7).
    Replaces the old frontend Math.random() placeholder trend charts on the
    Call Logs, Email Outreach, and WhatsApp pages with actual DB counts.
    """
    today = datetime.utcnow().date()
    day_list = [today - timedelta(days=i) for i in range(days - 1, -1, -1)]

    def _bucket(rows, date_field):
        """rows: list of datetime values -> dict{date: count}"""
        counts = {d: 0 for d in day_list}
        for value in rows:
            if value is None:
                continue
            d = value.date() if hasattr(value, "date") else value
            if d in counts:
                counts[d] += 1
        return counts

    email_sent_dates    = [r[0] for r in db.query(EmailLog.sent_at).all()]
    email_opened_dates  = [r[0] for r in db.query(EmailLog.opened_at).filter(EmailLog.opened_at.isnot(None)).all()]
    email_replied_dates = [r[0] for r in db.query(EmailLog.replied_at).filter(EmailLog.replied_at.isnot(None)).all()]

    call_dates        = [r[0] for r in db.query(CallLog.called_at).all()]
    call_interested_dates = [
        r[0] for r in db.query(CallLog.called_at).filter(CallLog.outcome == CallOutcome.INTERESTED).all()
    ]

    wa_sent_dates    = [r[0] for r in db.query(WhatsAppLog.sent_at).all()]
    wa_replied_dates = [r[0] for r in db.query(WhatsAppLog.replied_at).filter(WhatsAppLog.replied_at.isnot(None)).all()]

    sent_by_day     = _bucket(email_sent_dates, "sent_at")
    opened_by_day   = _bucket(email_opened_dates, "opened_at")
    replied_by_day  = _bucket(email_replied_dates, "replied_at")
    calls_by_day    = _bucket(call_dates, "called_at")
    interested_by_day = _bucket(call_interested_dates, "called_at")
    wa_sent_by_day    = _bucket(wa_sent_dates, "sent_at")
    wa_replied_by_day = _bucket(wa_replied_dates, "replied_at")

    def _label(d):
        return d.strftime("%a")  # Mon, Tue, ...

    return {
        "emails": [
            {"day": _label(d), "date": d.isoformat(), "sent": sent_by_day[d], "opened": opened_by_day[d], "replied": replied_by_day[d]}
            for d in day_list
        ],
        "calls": [
            {"day": _label(d), "date": d.isoformat(), "calls": calls_by_day[d], "interested": interested_by_day[d]}
            for d in day_list
        ],
        "whatsapp": [
            {"day": _label(d), "date": d.isoformat(), "sent": wa_sent_by_day[d], "replied": wa_replied_by_day[d]}
            for d in day_list
        ],
    }


