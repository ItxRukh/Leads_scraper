@app.get("/notifications", tags=["Notifications"])
def get_notifications(db: Session = Depends(get_db)):
    """
    Returns unread items for the admin bell icon:
      - Email replies (from Instantly's reply events) not yet reviewed, with the AI's label
        (interested, question, not now, stop, other) and its one-line summary
      - A weekly digest: leads scraped in the last 7 days that have no email address and have not been contacted

    Each item includes a content preview so the admin can see what
    happened without opening the full CRM page first.
    """
    items = []

    email_replies = (
        db.query(EmailLog)
        .filter(EmailLog.replied == True)
        .order_by(EmailLog.replied_at.desc())
        .limit(50)
        .all()
    )
    from database import InboundMessage
    for log in email_replies:
        lead = db.query(Lead).filter(Lead.id == log.lead_id).first()
        inbound = db.query(InboundMessage).filter(InboundMessage.lead_id == log.lead_id, InboundMessage.kind == "reply") \
            .order_by(InboundMessage.id.desc()).first()
        items.append({
            "type": "email_reply",
            "id": log.id,
            "lead_id": log.lead_id,
            "lead_name": lead.name if lead else "Unknown",
            "label": inbound.label if inbound else None,
            "preview": (inbound.summary if inbound and inbound.summary else (log.reply_content or ""))[:140],
            "full_content": log.reply_content or "",
            "timestamp": log.replied_at.isoformat() + "Z" if log.replied_at else None,
            "is_read": log.is_read,
        })

    digest_item = _build_weekly_no_email_digest(db)
    if digest_item:
        items.append(digest_item)

    # Newest first, across all types combined
    items.sort(key=lambda x: x["timestamp"] or "", reverse=True)

    unread_count = sum(1 for i in items if not i["is_read"])

    return {
        "unread_count": unread_count,
        "items": items,
    }


def _build_weekly_no_email_digest(db: Session) -> Optional[dict]:
    """
    Feature 7 — Daily Digest Notification.

    Counts leads scraped in the last 7 days that have NO email on file
    and have never had any outreach attempt logged against them (no
    EmailLog — impossible without an email anyway — no WhatsAppLog, no
    CallLog). These are exactly the leads Smart First-Touch Routing
    hasn't reached yet (below the warm/hot threshold, so no automatic
    SMS/call has fired for them either).

    Returns None if there are none this week (no notification needed).

    Read/unread is tracked with a single rolling timestamp
    (`digestReadAt` in app_settings) instead of a per-item DB row —
    the digest is "read" once the admin has opened the bell any time
    since this week's 7-day window started, and automatically flips
    back to unread once the window rolls forward past that ack.
    """
    from app_settings import get_app_settings
    week_start = datetime.utcnow() - timedelta(days=7)

    contacted_email_ids = {r[0] for r in db.query(EmailLog.lead_id).all()}
    contacted_sms_ids = {r[0] for r in db.query(WhatsAppLog.lead_id).all()}
    contacted_call_ids = {r[0] for r in db.query(CallLog.lead_id).all()}
    already_contacted = contacted_email_ids | contacted_sms_ids | contacted_call_ids

    query = db.query(Lead).filter(
        Lead.scraped_at >= week_start,
        (Lead.email == None) | (Lead.email == ""),
    )
    if already_contacted:
        query = query.filter(~Lead.id.in_(already_contacted))

    leads = query.order_by(Lead.scraped_at.desc()).all()
    if not leads:
        return None

    settings_data = get_app_settings()
    read_at_raw = settings_data.get("digestReadAt")
    is_read = False
    if read_at_raw:
        try:
            read_at = datetime.fromisoformat(read_at_raw)
            is_read = read_at >= week_start
        except ValueError:
            is_read = False

    preview_names = ", ".join(l.name for l in leads[:5])
    more = f" and {len(leads) - 5} more" if len(leads) > 5 else ""

    return {
        "type": "no_email_digest",
        "id": "weekly-no-email-digest",
        "lead_id": None,
        "lead_name": None,
        "preview": f"{len(leads)} leads this week couldn't be contacted (no email found)",
        "full_content": (
            f"{len(leads)} leads scraped in the last 7 days have no email on file "
            f"and haven't been reached by any channel yet: {preview_names}{more}. "
            f"Click 'View leads' to see the full list (Stuck Leads filter)."
        ),
        "timestamp": leads[0].scraped_at.isoformat() if leads[0].scraped_at else None,
        "is_read": is_read,
    }


@app.post("/notifications/mark-read", tags=["Notifications"])
def mark_notifications_read(db: Session = Depends(get_db)):
    """
    Marks every unread email reply as read.
    Also acknowledges this week's "no email found" digest (Feature 7) —
    it stays read until the rolling 7-day window moves past this timestamp.
    Called when the admin opens the notification bell dropdown.
    """
    db.query(EmailLog).filter(EmailLog.is_read == False).update({"is_read": True})
    db.query(WhatsAppLog).filter(WhatsAppLog.is_read == False).update({"is_read": True})
    db.query(CallLog).filter(CallLog.is_read == False).update({"is_read": True})
    db.commit()

    from app_settings import save_app_settings
    save_app_settings({"digestReadAt": datetime.utcnow().isoformat()})

    return {"status": "ok"}


