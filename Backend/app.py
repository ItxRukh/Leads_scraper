@app.get("/email-logs", tags=["Email"])
def get_email_logs(
    lead_id: Optional[int] = None,
    search:  Optional[str] = Query(None, description="Free-text search across subject, recipient, lead name/email"),
    status:  Optional[str] = Query(None, description="Filter by status: sent | opened | replied | unsubscribed"),
    year:    Optional[int] = Query(None, ge=2000, le=2100, description="Filter by sent_at year. Combine with month for a single month."),
    month:   Optional[int] = Query(None, ge=1, le=12, description="Filter by sent_at month (1-12). Requires year."),
    skip:    int = 0,
    limit:   int = 100,
    db: Session = Depends(get_db),
):
    """
    Returns email outreach history.
    Optionally filter by lead_id, free-text search, delivery status, or
    a calendar year/month (via `sent_at`).
    """
    query = db.query(EmailLog)
    if lead_id:
        query = query.filter(EmailLog.lead_id == lead_id)

    if year is not None:
        if month is not None:
            since = datetime(year, month, 1)
            until = datetime(year + 1, 1, 1) if month == 12 else datetime(year, month + 1, 1)
        else:
            since = datetime(year, 1, 1)
            until = datetime(year + 1, 1, 1)
        query = query.filter(EmailLog.sent_at >= since, EmailLog.sent_at < until)

    if search:
        like = f"%{search}%"
        query = query.join(Lead, EmailLog.lead_id == Lead.id).filter(
            EmailLog.subject.ilike(like) |
            EmailLog.personalized_for.ilike(like) |
            EmailLog.campaign_id.ilike(like) |
            Lead.name.ilike(like) |
            Lead.email.ilike(like)
        )

    # Status is derived the same way the frontend derives it per-row:
    # unsubscribed > replied > opened > sent (fallback)
    if status == "unsubscribed":
        query = query.filter(EmailLog.unsubscribed == True)
    elif status == "replied":
        query = query.filter(EmailLog.replied == True, EmailLog.unsubscribed == False)
    elif status == "opened":
        query = query.filter(
            EmailLog.email_opened == True,
            EmailLog.replied == False,
            EmailLog.unsubscribed == False,
        )
    elif status == "sent":
        query = query.filter(
            EmailLog.email_opened == False,
            EmailLog.replied == False,
            EmailLog.unsubscribed == False,
        )
    elif status == "bounced":
        # No "bounced" tracking field exists yet on EmailLog — nothing to match.
        query = query.filter(False)

    total = query.count()
    logs = query.order_by(EmailLog.sent_at.desc()).offset(skip).limit(limit).all()
    return {"total": total, "logs": [_serialize_email_log(log) for log in logs]}


@app.get("/email-logs/export", tags=["Email"])
def export_email_logs(
    search: Optional[str] = None,
    status: Optional[str] = None,
    db: Session = Depends(get_db),
):
    """Exports email outreach logs (respecting current search/status filters) to CSV."""
    query = db.query(EmailLog)
    if search:
        like = f"%{search}%"
        query = query.join(Lead, EmailLog.lead_id == Lead.id).filter(
            EmailLog.subject.ilike(like) |
            EmailLog.personalized_for.ilike(like) |
            EmailLog.campaign_id.ilike(like) |
            Lead.name.ilike(like) |
            Lead.email.ilike(like)
        )
    if status == "unsubscribed":
        query = query.filter(EmailLog.unsubscribed == True)
    elif status == "replied":
        query = query.filter(EmailLog.replied == True, EmailLog.unsubscribed == False)
    elif status == "opened":
        query = query.filter(EmailLog.email_opened == True, EmailLog.replied == False, EmailLog.unsubscribed == False)
    elif status == "sent":
        query = query.filter(EmailLog.email_opened == False, EmailLog.replied == False, EmailLog.unsubscribed == False)
    elif status == "bounced":
        query = query.filter(False)

    logs = query.order_by(EmailLog.sent_at.desc()).all()
    rows = [_serialize_email_log(log) for log in logs]
    columns = ["id", "lead_id", "campaign_id", "subject", "personalized_for",
               "email_opened", "opened_at", "replied", "replied_at",
               "unsubscribed", "sent_at"]
    path = export_logs_to_csv(rows, columns, "email_logs")
    if not path:
        raise HTTPException(status_code=404, detail="No email logs to export")
    return FileResponse(path=path, media_type="text/csv", filename=os.path.basename(path))


