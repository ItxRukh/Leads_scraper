# ─── Logging + Error Monitoring ────────────────────────────────────────────────
# Two layers, so you're never blind in production:
#   1. Rotating file logs (logs/app.log, logs/errors.log) — always on, free.
#      Previously the app only logged to the console, which meant nothing
#      survived after the terminal was closed or the process restarted.
#   2. Sentry (optional) — only activates if SENTRY_DSN is set in .env.
#      Sends unhandled exceptions + logger.error()/critical() calls with
#      full stack traces so you find out about crashes immediately instead
#      of waiting for a user to report them.

LOG_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logs")


def _setup_file_logging() -> None:
    os.makedirs(LOG_DIR, exist_ok=True)

    logger.remove()
    logger.add(sys.stderr, level="INFO", colorize=True)

    logger.add(
        os.path.join(LOG_DIR, "app.log"),
        level="INFO",
        rotation="10 MB",
        retention="14 days",
        compression="zip",
        backtrace=True,
        diagnose=False,   # keep False in prod — True would leak variable values into logs
        enqueue=True,      # thread/process-safe (APScheduler runs in a background thread)
    )

    # Separate errors-only file — faster to grep after an incident.
    logger.add(
        os.path.join(LOG_DIR, "errors.log"),
        level="ERROR",
        rotation="10 MB",
        retention="30 days",
        compression="zip",
        backtrace=True,
        diagnose=False,
        enqueue=True,
    )

    logger.info(f"File logging active → {LOG_DIR}/app.log (errors.log for ERROR+)")


def _setup_sentry() -> None:
    if not settings.SENTRY_DSN:
        logger.info("SENTRY_DSN not set — skipping Sentry (file logs still active).")
        return

    try:
        import sentry_sdk
        from sentry_sdk.integrations.fastapi import FastApiIntegration
        from sentry_sdk.integrations.loguru import LoguruIntegration

        sentry_sdk.init(
            dsn=settings.SENTRY_DSN,
            environment=settings.APP_ENV,
            integrations=[FastApiIntegration(), LoguruIntegration()],
            traces_sample_rate=0.1,
            send_default_pii=False,
        )
        logger.info("Sentry error monitoring active.")
    except ImportError:
        logger.warning(
            "SENTRY_DSN is set but 'sentry-sdk' is not installed. "
            "Run: pip install 'sentry-sdk[fastapi]' to enable it."
        )


_setup_file_logging()
_setup_sentry()

